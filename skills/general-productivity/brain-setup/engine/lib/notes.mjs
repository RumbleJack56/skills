// Item index over project notes: reindex, brief, get, find, grep. Items are level-2 headings.
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { readDoc, safeRead, tx } from "./store.mjs";
import { slugify, clean, fence } from "./util.mjs";
import { parseFrontmatter } from "./brain.mjs";

const START = "<!-- brain-index";
const q = (s) => JSON.stringify(s);

function layout(lines) {
  const fmEnd = lines[0] === "---" ? (lines.indexOf("---", 1) + 1 || 0) : 0;
  let idxEnd = fmEnd;
  if (lines[fmEnd]?.startsWith(START)) {
    let j = fmEnd;
    while (j < lines.length && lines[j].trim() !== "-->") j++;
    idxEnd = Math.min(j + 1, lines.length);
  }
  return { fmEnd, idxEnd };
}

export function itemsOf(lines) {
  const { idxEnd } = layout(lines);
  const found = [];
  let fence = false;
  for (let i = idxEnd; i < lines.length; i++) {
    if (/^\s*(```|~~~)/.test(lines[i])) fence = !fence;
    const m = !fence && /^## (.+?)\s*$/.exec(lines[i]);
    if (m) found.push({ name: m[1], start: i });
  }
  const top = lines.slice(idxEnd, found[0]?.start ?? lines.length).join("\n").trim();
  if (top) found.unshift({ name: "Top", start: idxEnd, top: true });
  const seen = new Map();
  found.forEach((it, n) => {
    it.end = found[n + 1]?.start ?? lines.length;
    const base = it.top ? "_top" : slugify(it.name) || "item";
    const c = (seen.get(base) ?? 0) + 1;
    seen.set(base, c);
    it.slug = c > 1 ? `${base}-${c}` : base;
    const body = lines.slice(it.top ? it.start : it.start + 1, it.end);
    const d = body.find((l) => l.trim());
    it.desc = d?.startsWith("> ") ? d.slice(2).trim() : "";
    it.lines = it.end - it.start;
    it.tokens = Math.ceil(lines.slice(it.start, it.end).join("\n").length / 4);
  });
  return found;
}

function indexBlock(its) {
  const out = [START + " (generated by brain reindex; do not edit)", "items = ["];
  for (const it of its) out.push(`  { slug = ${q(it.slug)}, line = ${it.start + 1}, lines = ${it.lines}, tokens = ${it.tokens}, desc = ${q(it.desc)} },`);
  out.push("]", "-->");
  return out;
}

export function reindexText(text) {
  let cur = text;
  for (let pass = 0; pass < 4; pass++) {
    const lines = cur.split("\n");
    if (lines[0] === "---" && lines.indexOf("---", 1) < 0) throw new Error("frontmatter is not closed; refusing to touch the file");
    const { fmEnd, idxEnd } = layout(lines);
    const next = [...lines.slice(0, fmEnd), ...indexBlock(itemsOf(lines)), ...lines.slice(idxEnd)].join("\n");
    if (next === cur) break;
    cur = next;
  }
  return cur;
}

// Markdown files of the brain that hold items (never dot-folders, never symlinks that leave the brain).
export function walkMd(root, dirs, visit) {
  const base = fs.realpathSync(root);
  const go = (dir) => {
    let ents;
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of ents.sort((a, b) => a.name.localeCompare(b.name))) {
      if (e.name.startsWith(".") || e.name === "node_modules") continue;
      const p = path.join(dir, e.name);
      let real;
      try { real = fs.realpathSync(p); } catch { continue; }
      if (real !== base && !real.startsWith(base + path.sep)) continue;
      const st = fs.statSync(p);
      if (st.isDirectory()) go(p);
      else if (e.name.endsWith(".md")) visit(p);
    }
  };
  for (const d of dirs) { const p = path.join(root, d); if (fs.existsSync(p)) go(p); }
}
export const KNOWLEDGE_DIRS = ["projects", "kb", "notes"];

export function reindexAll(brain, target) {
  const files = [];
  if (target) files.push(path.resolve(brain, target));
  else walkMd(brain, KNOWLEDGE_DIRS, (f) => {
    if (/(^|\/)tasks(\.now)?\.md$/.test(f)) return;
    const d = safeRead(f);
    if (d && (d.text.includes(START) || itemsOf(d.text.split("\n")).some((i) => !i.top))) files.push(f);
  });
  const out = [];
  for (const f of files) {
    const doc = readDoc(f);
    let next;
    try { next = reindexText(doc.text); } catch (e) { out.push(`error ${path.relative(brain, f)}: ${e.message}`); continue; }
    if (next !== doc.text) { tx(brain, "reindex", (t) => t.edit(path.relative(brain, f), () => next)); out.push(`updated ${path.relative(brain, f)}`); }
  }
  return out;
}

// ---- safe path for get: relative, inside the brain, in a knowledge folder ----
export function resolveNote(root, spec) {
  if (!spec || path.isAbsolute(spec) || spec.split(/[\\/]/).includes("..")) throw new Error(`path "${spec}" is not allowed (use project/file or kb/..., no absolute paths or "..")`);
  let rel = spec.endsWith(".md") ? spec : `${spec}.md`;
  const top = rel.split("/")[0];
  if (!["projects", "kb", "notes", "daily", "routines", "inbox"].includes(top)) rel = path.join("projects", rel);
  const abs = path.join(root, rel);
  let real;
  try { real = fs.realpathSync(abs); } catch { throw new Error(`no such note: ${rel}`); }
  const base = fs.realpathSync(root);
  if (!real.startsWith(base + path.sep)) throw new Error(`${rel} resolves outside the brain`);
  return { abs: real, rel };
}

export function getItem(root, spec, slug) {
  const { abs, rel } = resolveNote(root, spec);
  const lines = readDoc(abs).text.split("\n");
  const its = itemsOf(lines);
  const it = its.find((i) => i.slug === slug);
  if (!it) throw new Error(`no item "${slug}" in ${rel}. Items: ${its.map((i) => i.slug).join(", ") || "(none)"}`);
  return `${rel} > ${it.slug}\n` + fence(lines.slice(it.start, it.end).join("\n").trimEnd());
}

export function briefOf(root, spec) {
  const { abs, rel } = resolveNote(root, spec);
  const lines = readDoc(abs).text.split("\n");
  const { fm } = parseFrontmatter(lines.join("\n"));
  const { fmEnd } = layout(lines);
  const out = [`${rel}`, ...lines.slice(0, fmEnd).map(clean)];
  for (const it of itemsOf(lines)) out.push(`${it.slug.padEnd(24)} ${String(it.lines).padStart(4)} lines ~${String(it.tokens).padStart(5)} tok  ${clean(it.desc)}`);
  return { text: out.join("\n"), fm };
}

export function findItems(root, words, limit = 8) {
  const norm = (w) => w.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]+/g, "").replace(/[^\p{L}\p{N}\p{M}]/gu, "").replace(/s$/, "");
  const terms = [...new Set(words.join(" ").split(/\s+/).map(norm).filter((w) => [...w].length > 1))];
  const hit = (text, t) => text.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]+/g, "").replace(/s\b/g, "").includes(t);
  const results = [];
  let files = 0;
  walkMd(root, KNOWLEDGE_DIRS, (f) => {
    const doc = safeRead(f);
    if (!doc) return;
    files++;
    const lines = doc.text.split("\n");
    const rel = path.relative(root, f).replace(/\.md$/, "");
    for (const it of itemsOf(lines)) {
      const body = lines.slice(it.start, it.end).join("\n");
      let score = 0; const where = new Set(); let miss = 0;
      for (const t of terms) {
        if (hit(it.slug + " " + it.name, t)) { score += 3; where.add("name"); }
        else if (hit(it.desc, t)) { score += 2; where.add("desc"); }
        else if (hit(body, t)) { score += 1; where.add("body"); }
        else miss++;
      }
      if (score) results.push({ score: score - miss * 0.5, rel, it, where: [...where] });
    }
  });
  results.sort((a, b) => b.score - a.score || a.it.tokens - b.it.tokens);
  const lines = results.slice(0, limit).map((r) => `${r.rel} > ${r.it.slug} (~${r.it.tokens} tok) [${r.where.join("+")}] ${clean(r.it.desc)}`);
  if (!lines.length) lines.push("no items match. Try fewer or different words, or: brain grep <regex>");
  lines.push(`coverage: ${files} files searched`);
  return lines.join("\n");
}

// ---- grep: ripgrep with an allowlist of flags ----
const GREP_BOOL = new Set(["-i", "-w", "-F", "-v", "-P", "-U"]);
const GREP_NUM = new Set(["-A", "-B", "-C"]);
export function grep(root, argv) {
  const o = { l: false, c: false, o: false, m: Infinity, limit: 200, sed: [], pass: [], pattern: null };
  const pos = [];
  for (let k = 0; k < argv.length; k++) {
    const x = argv[k];
    if (x === "-m") { o.m = Number(argv[++k]); if (!Number.isInteger(o.m) || o.m < 1) throw new Error("-m needs a positive number"); }
    else if (x === "--limit") o.limit = Math.min(1000, Math.max(1, Number(argv[++k]) || 200));
    else if (x === "--sed") o.sed.push(argv[++k] ?? "");
    else if (x === "-e") o.pattern = argv[++k];
    else if (GREP_NUM.has(x)) { const n = argv[++k]; if (!/^\d{1,3}$/.test(n ?? "")) throw new Error(`${x} needs a number`); o.pass.push(x, n); }
    else if (/^-[ABC]\d{1,3}$/.test(x)) o.pass.push(x);
    else if (GREP_BOOL.has(x)) o.pass.push(x);
    else if (/^-[a-zA-Z]{2,}$/.test(x)) {
      for (const ch of x.slice(1)) {
        if ("lco".includes(ch)) o[ch] = true;
        else if (GREP_BOOL.has("-" + ch)) o.pass.push("-" + ch);
        else throw new Error(`grep flag -${ch} is not allowed`);
      }
    } else if (x.startsWith("-") && x !== "-") throw new Error(`grep flag ${x} is not allowed (allowed: -i -w -F -v -P -U -A -B -C -m -l -c -o --sed --limit)`);
    else pos.push(x);
  }
  if (o.pattern === null) o.pattern = pos.shift();
  if (o.pattern === undefined || pos.length) throw new Error("usage: brain grep [flags] <regex>");
  const rg = spawnSync("rg", ["--no-config", "--json", "--no-follow", "--sort", "path", ...o.pass, "-e", o.pattern, "--glob", "*.md", "--", ...KNOWLEDGE_DIRS.concat(["inbox", "daily", "routines"]).filter((d) => fs.existsSync(path.join(root, d)))], { cwd: root, encoding: "buffer", maxBuffer: 256 << 20, timeout: 5000 });
  if (rg.error?.code === "ENOENT") throw new Error("ripgrep (rg) is required: https://github.com/BurntSushi/ripgrep#installation");
  if (rg.error?.code === "ETIMEDOUT") throw new Error("grep took longer than 5 s; narrow the pattern");
  const stdout = rg.stdout.toString("utf8");
  if (rg.status === 2 && !stdout.includes('"type":"match"')) throw new Error(rg.stderr.toString().trim() || "rg failed");
  const byFile = new Map();
  const textOf = (d) => (d.text !== undefined ? d.text : d.bytes !== undefined ? Buffer.from(d.bytes, "base64").toString("latin1") : "");
  for (const raw of stdout.split("\n")) {
    if (!raw) continue;
    let ev; try { ev = JSON.parse(raw); } catch { continue; }
    if (ev.type !== "match" && ev.type !== "context") continue;
    const f = textOf(ev.data.path ?? {}), t = textOf(ev.data.lines ?? {});
    const isMatch = ev.type === "match";
    const subs = (ev.data.submatches ?? []).map((s) => textOf(s.match).replace(/\n/g, "⏎"));
    const list = byFile.get(f) ?? byFile.set(f, []).get(f);
    t.replace(/\n$/, "").split("\n").forEach((text, i) => list.push({ n: ev.data.line_number - 1 + i, text, isMatch, cont: isMatch && i > 0, subs: i === 0 ? subs : [] }));
  }
  const groups = [];
  let files = 0;
  for (const [f, entries] of byFile) {
    const doc = safeRead(path.join(root, f));
    if (!doc) continue;
    files++;
    const lines = doc.text.split("\n");
    const its = itemsOf(lines), seen = new Set(), by = new Map();
    for (const e of entries.sort((x, y) => x.n - y.n)) {
      if (seen.has(e.n)) continue; seen.add(e.n);
      const it = its.find((x) => e.n >= x.start && e.n < x.end) ?? { slug: "_top", desc: "" };
      (by.get(it) ?? by.set(it, []).get(it)).push(e);
    }
    for (const [it, es] of by) {
      let hits = 0; const keep = [];
      for (const e of es) { if (e.isMatch) { if (hits >= o.m) continue; hits++; } keep.push(e); }
      if (hits) groups.push({ f: f.replace(/\.md$/, ""), it, es: keep, hits });
    }
  }
  if (o.o) for (const g of groups) g.es = g.es.filter((e) => !e.cont);
  const show = (e) => (o.o && e.isMatch && e.subs.length ? e.subs.join(" | ") : e.text.trim());
  if (o.sed.length) {
    const all = groups.flatMap((g) => g.es);
    const texts = all.map(show);
    const args = o.sed.flatMap((x) => ["-e", x]);
    const run = (input, z) => spawnSync("sed", ["--sandbox", "-E", ...(z ? ["-z"] : []), ...args], { input, encoding: "utf8", timeout: 5000 });
    let res = null;
    const batch = run(texts.join("\0") + "\0", true);
    if (batch.error) throw new Error(batch.error.code === "ETIMEDOUT" ? "--sed took longer than 5 s" : batch.error.message);
    if (batch.status === 0) { const parts = batch.stdout.split("\0"); parts.pop(); if (parts.length === texts.length) res = parts; }
    if (!res) res = texts.map((t) => { const r = run(t + "\n", false); if (r.error) throw new Error("--sed took longer than 5 s"); if (r.status !== 0) throw new Error(r.stderr.trim() || "sed failed"); return r.stdout.length ? r.stdout.replace(/\n$/, "") : null; });
    all.forEach((e, i) => { e.out = res[i]; });
    for (const g of groups) g.es = g.es.filter((e) => e.out !== null);
  } else for (const g of groups) for (const e of g.es) e.out = show(e);
  const live = groups.filter((g) => g.es.some((e) => e.isMatch));
  const out = []; let truncated = false;
  const emit = (s) => { if (out.length < o.limit) out.push(s); else truncated = true; };
  for (const g of live) {
    const head = `${g.f} > ${g.it.slug}${g.it.desc ? " - " + clean(g.it.desc) : ""}`;
    if (o.l) { emit(head); continue; }
    if (o.c) { emit(`${head}  [${g.hits} hit${g.hits > 1 ? "s" : ""}]`); continue; }
    emit(head);
    let prev = -2;
    for (const e of g.es) { if (prev >= 0 && e.n > prev + 1) emit("  --"); emit(`  ${e.n + 1}${e.isMatch ? ":" : "-"} ${clean(e.out)}`); prev = e.n; }
  }
  if (!out.length) out.push("(no matches)");
  if (truncated) out.push(`... truncated at ${o.limit} lines. Narrow with -m, -l, -c.`);
  out.push(`coverage: ${files} files with hits`);
  return fence(out.join("\n"));
}
